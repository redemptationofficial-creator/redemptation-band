let currentAudio = null;
let currentButton = null;

function createTrackElement(track, folder) {
  const div = document.createElement('div');
  div.className = 'track';
  
  const title = document.createElement('div');
  title.className = 'track-title';
  title.innerHTML = `<span>▶</span> ${track.title}`;
  
  const btn = document.createElement('button');
  btn.className = 'play-btn';
  
  // Перевод кнопки в зависимости от языка
  btn.textContent = currentLang.startsWith('en') ? 'Listen' : (currentLang.startsWith('zh') ? '试听' : 'Слушать');
  
  btn.addEventListener('click', () => {
    if (currentAudio) {
      currentAudio.pause();
      currentAudio = null;
      if (currentButton) {
        currentButton.textContent = currentLang.startsWith('en') ? 'Listen' : (currentLang.startsWith('zh') ? '试听' : 'Слушать');
        currentButton.disabled = false;
      }
    }
    
    if (currentButton === btn) {
      currentButton = null;
      return;
    }
    
    btn.textContent = '...';
    btn.disabled = true;
    
    const audioUrl = folder + track.file;
    
    fetch(audioUrl)
      .then(response => {
          if (!response.ok) throw new Error("File not found");
          return response.blob();
      })
      .then(blob => {
        const blobUrl = URL.createObjectURL(blob);
        const audio = new Audio(blobUrl);
        
        audio.addEventListener('ended', () => {
          btn.textContent = currentLang.startsWith('en') ? 'Listen' : (currentLang.startsWith('zh') ? '试听' : 'Слушать');
          btn.disabled = false;
          currentAudio = null;
          currentButton = null;
        });
        
        audio.play();
        currentAudio = audio;
        currentButton = btn;
        btn.textContent = currentLang.startsWith('en') ? 'Playing' : (currentLang.startsWith('zh') ? '播放中' : 'Играет');
        btn.disabled = false;
      })
      .catch(err => {
        console.error('Error:', err);
        btn.textContent = 'Error';
        btn.disabled = false;
      });
  });
  
  div.appendChild(title);
  div.appendChild(btn);
  return div;
}

function createMemberCard(member) {
  const div = document.createElement('div');
  div.className = 'band-member';
  
  const img = document.createElement('img');
  img.src = member.img;
  img.alt = member.name;
  
  const name = document.createElement('p');
  name.innerHTML = `<strong>${member.name}</strong><br>${member.role}`;
  
  div.appendChild(img);
  div.appendChild(name);
  return div;
}

function renderAll() {
  const trackList = document.getElementById('track-list');
  if (trackList) {
    redemptationTracks.forEach(track => {
      trackList.appendChild(createTrackElement(track, 'audio/previews/'));
    });
  }
  
  const quintetList = document.getElementById('quintet-list');
  if (quintetList) {
    quintetTracks.forEach(track => {
      quintetList.appendChild(createTrackElement(track, 'audio/quintet/'));
    });
  }
  
  const bandList = document.getElementById('band-list');
  if (bandList) {
    bandMembers.forEach(m => bandList.appendChild(createMemberCard(m)));
  }
  
  const quintetPhotos = document.getElementById('quintet-photos');
  if (quintetPhotos) {
    quintetMembers.forEach(m => quintetPhotos.appendChild(createMemberCard(m)));
  }
}

